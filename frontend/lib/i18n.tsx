const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("vi");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    let cancelled = false;

    async function loadLanguage() {
      const storedLanguage = localStorage.getItem(
        LANGUAGE_KEY,
      ) as Language | null;

      if (storedLanguage === "en" || storedLanguage === "vi") {
        if (!cancelled) setLanguageState(storedLanguage);
      } else {
        const desktopPreference = await window.ocrDesktop
          ?.getLanguagePreference()
          .catch(() => undefined);
        if (
          !cancelled &&
          (desktopPreference === "en" || desktopPreference === "vi")
        ) {
          setLanguageState(desktopPreference);
        }
      }

      if (!cancelled) setReady(true);
    }

    void loadLanguage();

    return () => {
      cancelled = true;
    };
  }, []);

  useEffect(() => {
    if (!ready) {
      return;
    }

    localStorage.setItem(LANGUAGE_KEY, language);
    document.documentElement.lang = language;
    void window.ocrDesktop
      ?.setLanguagePreference(language)
      .catch(() => undefined);
  }, [language, ready]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage: setLanguageState,
      t: (key) => {
        const currentTranslations = translations[language] as Record<
          string,
          string
        >;
        const englishTranslations = translations.en as Record<string, string>;
        const currentOverrides = translationOverrides[language] ?? {};
        const englishOverrides = translationOverrides.en ?? {};

        return (
          currentOverrides[key] ??
          currentTranslations[key] ??
          englishOverrides[key] ??
          englishTranslations[key] ??
          key
        );
      },
      apiError: (message, fallbackKey) => {
        const currentTranslations = translations[language] as Record<
          string,
          string
        >;
        const englishTranslations = translations.en as Record<string, string>;
        const normalizedMessage = message.trim();
        const apiErrorKey = `apiError.${normalizedMessage}`;

        return (
          currentTranslations[apiErrorKey] ??
          englishTranslations[apiErrorKey] ??
          currentTranslations[fallbackKey] ??
          englishTranslations[fallbackKey] ??
          normalizedMessage
        );
      },
    }),
    [language],
  );

  return (
    <I18nContext.Provider value={value}>
      {ready ? (
        children
      ) : (
        <main className="flex min-h-[100dvh] items-center justify-center bg-slate-100 text-slate-950">
          <div className="h-10 w-10 animate-spin rounded-full border-2 border-slate-300 border-t-slate-900" />
        </main>
      )}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return context;
}
